import Foundation

struct GenerationError: Error, CustomStringConvertible {
  let description: String
}

/// A one-shot build tool. Parsing may allocate; the generated runtime lookup does not.
@main
struct UnicodeWidthGenerator {
  static let maximumInputBytes = 1_048_576
  static let maximumRanges = 1_024

  static func main() {
    do {
      guard CommandLine.arguments.count == 3 else {
        throw GenerationError(description: "usage: UnicodeWidthGenerator EastAsianWidth.txt output.swift")
      }
      let file = try FileHandle(forReadingFrom: URL(fileURLWithPath: CommandLine.arguments[1]))
      // Read one extra byte to detect capacity exhaustion without loading an unbounded file.
      let data = try file.read(upToCount: maximumInputBytes + 1) ?? Data()
      try file.close()
      guard data.count <= maximumInputBytes else {
        throw GenerationError(description: "Unicode input exceeds \(maximumInputBytes) bytes")
      }
      guard let input = String(data: data, encoding: .utf8) else {
        throw GenerationError(description: "Unicode input is not valid UTF-8")
      }
      let output = try generate(input)
      try output.write(toFile: CommandLine.arguments[2], atomically: true, encoding: .utf8)
    } catch let error as GenerationError {
      fail(error.description)
    } catch {
      fail(error.localizedDescription)
    }
  }

  private static func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("error: \(message)\n".utf8))
    exit(EXIT_FAILURE)
  }

  static func generate(_ input: String) throws(GenerationError) -> String {
    guard input.utf8.count <= maximumInputBytes else {
      throw GenerationError(description: "Unicode input exceeds \(maximumInputBytes) bytes")
    }
    guard input.hasPrefix("# EastAsianWidth-18.0.0.txt\n") else {
      throw GenerationError(description: "expected Unicode 18.0.0 EastAsianWidth.txt")
    }
    var ranges: [(lower: UInt32, upper: UInt32)] = []
    ranges.reserveCapacity(maximumRanges)
    var previousUpper: UInt32?
    for (index, line) in input.split(separator: "\n", omittingEmptySubsequences: false).enumerated() {
      let body = line.split(separator: "#", maxSplits: 1, omittingEmptySubsequences: false)[0]
        .trimmingCharacters(in: .whitespaces)
      if body.isEmpty { continue }
      let fields = body.split(separator: ";", omittingEmptySubsequences: false)
        .map { $0.trimmingCharacters(in: .whitespaces) }
      guard fields.count == 2 else {
        throw GenerationError(description: "invalid Unicode property record at line \(index + 1)")
      }
      let limits = fields[0].components(separatedBy: "..")
      guard (1...2).contains(limits.count),
        let lower = UInt32(limits[0], radix: 16),
        let upper = UInt32(limits[limits.count - 1], radix: 16),
        lower <= upper, upper <= 0x10ffff,
        previousUpper.map({ $0 < lower }) ?? true
      else {
        throw GenerationError(description: "invalid or unordered Unicode range at line \(index + 1)")
      }
      previousUpper = upper
      switch fields[1] {
      case "W", "F": break
      case "A", "H", "N", "Na": continue
      default:
        throw GenerationError(description: "unknown East Asian width at line \(index + 1)")
      }
      if let last = ranges.last, lower == last.upper + 1 {
        ranges[ranges.count - 1].upper = upper
      } else {
        guard ranges.count < maximumRanges else {
          throw GenerationError(description: "Unicode input exceeds \(maximumRanges) wide ranges")
        }
        ranges.append((lower, upper))
      }
    }
    guard !ranges.isEmpty else {
      throw GenerationError(description: "Unicode input contains no wide ranges")
    }
    var output = """
      // Generated by UnicodeWidthPlugin from Unicode 18.0.0. Do not edit.
      // EastAsianWidth.txt: https://www.unicode.org/Public/18.0.0/ucd/EastAsianWidth.txt
      // Unicode data copyright Unicode, Inc. See Unicode-LICENSE.txt.
      // Only W/F ranges are stored. Ambiguous width is deliberately one column.
      // A switch keeps the immutable table in the executable, with no lazy heap array.
      enum UnicodeWidth {
        static func isWide(_ value: UInt32) -> Bool {
          switch value {

      """
    // At most 1,024 case lines (under 48 bytes each), plus the fixed header/footer.
    output.reserveCapacity(65_536)
    for range in ranges {
      let lower = "0x" + String(range.lower, radix: 16)
      let upper = "0x" + String(range.upper, radix: 16)
      output += "    case " + (range.lower == range.upper ? lower : lower + "..." + upper) + ": return true\n"
    }
    output += "    default: return false\n    }\n  }\n}\n"
    return output
  }
}
